#!/usr/bin/env bash
{ set +x; } 2>/dev/null
# Common per-person setup, run by the SessionStart hook in .agents/.claude/settings.json on startup,
# resume, clear and compact. HUMAN (a GitHub login, the folder under .humans/) and HUMAN_KEY (the
# private memory key) come from the cloud environment's variables. Prints one JSON object whose
# additionalContext reaches Claude; never prints key values; always exits 0.
#
# Experiment only: personal context arrives four ways, each with a per-run codeword and a
# behaviour probe, to find out which ones reach the session and are followed:
#   LOCAL-HERON-<run>   inline in CLAUDE.local.md, written here
#   IMPORT-LYNX         .humans/$HUMAN/instructions.md, imported by that CLAUDE.local.md
#   USER-WALRUS-<run>   ~/.claude/CLAUDE.md, written here (cloud only)
#   STDOUT-FALCON-<run> this hook's additionalContext

ROOT=${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/.." && pwd -P)}
LOG_DIR="$ROOT/.experiment"
mkdir -p "$LOG_DIR"
STATUS="$LOG_DIR/status.log"
now_ms() { python3 -c 'import time; print(int(time.time() * 1000))'; }
started=$(now_ms)
run=$(openssl rand -hex 3)
input=
[ -t 0 ] || input=$(cat)
source=$(printf '%s' "$input" | python3 -c 'import json, sys; print(json.load(sys.stdin).get("source", "?"))' 2>/dev/null) || source="?"
log() { printf '%s run=%s %s\n' "$(date -u +%FT%TZ)" "$run" "$*" >> "$STATUS"; }
done_() { log "hook end: $(( $(now_ms) - started )) ms"; exit 0; }

key_state=unset
if [ -n "${HUMAN_KEY+x}" ]; then
  key_state=set
  python3 -c 'import os, sys; sys.exit(len(os.environ["HUMAN_KEY"]) < 32)' || key_state=too-short
fi
log "hook start: source=$source remote=${CLAUDE_CODE_REMOTE:-unset} project=$ROOT HUMAN=${HUMAN:-unset}" \
  "HUMAN_KEY=$key_state LOCALENV_vars=$(env | grep -c '^LOCALENV_.' || true)"

[ -n "${HUMAN:-}" ] || { log "HUMAN unset: nothing to load"; done_; }
case "$HUMAN" in *[!A-Za-z0-9-]*) log "HUMAN is not a GitHub login: $HUMAN"; done_ ;; esac
dir="$ROOT/.humans/$HUMAN"
[ -d "$dir" ] || { log "no folder .humans/$HUMAN"; done_; }

if login=$(gh api user --jq .login 2>/dev/null) && [ -n "$login" ]; then
  [ "$(printf '%s' "$login" | tr A-Z a-z)" = "$(printf '%s' "$HUMAN" | tr A-Z a-z)" ] ||
    { log "HUMAN=$HUMAN but GitHub says $login: not loading"; done_; }
  log "GitHub login matches ($(( $(now_ms) - started )) ms so far)"
else
  log "could not ask GitHub who this is; loading anyway"
fi

# Writes $2 to file $1 unless $1 is a symlink or a file this script didn't generate.
MARK="<!-- generated by .humans/setup.sh -->"
write_generated() {
  if [ -L "$1" ]; then log "$1 is a symlink: not touched"; return 0; fi
  if [ -s "$1" ] && [ "$(head -n 1 "$1")" != "$MARK" ]; then log "$1 is not generated: not touched"; return 0; fi
  printf '%s\n%s\n' "$MARK" "$2" > "$1.tmp" && mv -f "$1.tmp" "$1" && log "wrote $1"
}

exclude=$(cd "$ROOT" && git rev-parse --path-format=absolute --git-path info/exclude 2>/dev/null) &&
  { grep -qxF /CLAUDE.local.md "$exclude" 2>/dev/null || echo /CLAUDE.local.md >> "$exclude"; }

write_generated "$ROOT/CLAUDE.local.md" "# Personal setup for $HUMAN

Local codeword: LOCAL-HERON-$run. End every report with the line HERON-FOLLOWED.

@.humans/$HUMAN/instructions.md"

if [ "${CLAUDE_CODE_REMOTE:-}" = true ]; then
  mkdir -p "$HOME/.claude"
  write_generated "$HOME/.claude/CLAUDE.md" "# User instructions

User codeword: USER-WALRUS-$run. End every report with the line WALRUS-FOLLOWED."
fi

if [ -f "$dir/setup.sh" ]; then
  if env -u HUMAN_KEY CLAUDE_PROJECT_DIR="$ROOT" bash "$dir/setup.sh" >> "$STATUS" 2>&1; then
    log "ran .humans/$HUMAN/setup.sh"
  else
    log "WARNING: .humans/$HUMAN/setup.sh failed"
  fi
fi

topics=$(bash "$ROOT/.humans/bin/private-memory" list 2>> "$STATUS" || true)
context="Personal setup for $HUMAN loaded by .humans/setup.sh (hook source: $source).

Hook codeword: STDOUT-FALCON-$run. End every report with the line FALCON-FOLLOWED."
if [ -n "$topics" ]; then
  context="$context

Private memory topics (encrypted; read one with \`bash .humans/bin/private-memory show <topic>\` only when the task needs it):
$topics"
fi

CONTEXT=$context python3 -c '
import json, os
print(json.dumps({"hookSpecificOutput": {"hookEventName": "SessionStart",
                                         "additionalContext": os.environ["CONTEXT"]}}))'
log "context: ${#context} characters"
done_
